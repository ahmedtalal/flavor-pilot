import 'dart:io';

import 'package:path/path.dart' as p;

import '../models/main_mode.dart';
import '../models/project_config.dart';
import '../utils/env_fields.dart';
import '../utils/file_changes.dart';
import 'generator.dart';

/// Creates the Dart side of the flavors.
///
/// - Always writes `lib/flavors.dart`: an `AppFlavor` enum the app uses to
///   know which flavor it's running, e.g. `AppFlavor.current.appName`. Each
///   `env` key becomes a field, e.g. `AppFlavor.current.baseUrl`.
/// - In [MainMode.multiple], also creates `lib/main_<flavor>.dart` for every
///   flavor that doesn't have one yet.
///
/// `lib/main.dart` itself is never touched.
class DartGenerator extends Generator {
  DartGenerator({required super.projectDir, required super.logger});

  /// First line of every file we generate. Used to recognize our own files,
  /// so a hand-written `lib/flavors.dart` is never overwritten.
  static const generatedHeader =
      '// GENERATED BY flavorpilot. Edit flavorpilot.yaml, not this file.';

  @override
  String get label => 'Dart';

  @override
  void generate(ProjectConfig config, FileChanges changes) {
    _writeFlavorsFile(config, changes);
    if (config.mainMode == MainMode.multiple) {
      _writeMainFiles(config, changes);
    }
  }

  /// Writes `lib/flavors.dart`, replacing an older generated copy.
  void _writeFlavorsFile(ProjectConfig config, FileChanges changes) {
    final file = File(p.join(projectDir, 'lib', 'flavors.dart'));
    if (file.existsSync() &&
        !file.readAsStringSync().startsWith(generatedHeader)) {
      logger.warn(
        'lib/flavors.dart already exists and was not created by flavorpilot, '
        'so it was left unchanged.',
      );
      return;
    }

    // Every flavor has the same env keys (ConfigLoader checks this), so the
    // first flavor gives the list of fields.
    final envKeys = config.flavors.first.env.keys;
    final values = config.flavors
        .map((f) {
          final args = [
            "appName: '${_escape(f.appName ?? f.name)}'",
            for (final key in envKeys)
              '${envFieldName(key)}: ${_literal(f.env[key]!)}',
          ];
          return '  ${f.name}(${args.join(', ')})';
        })
        .join(',\n');
    final parameters = [
      'required this.appName',
      for (final key in envKeys) 'required this.${envFieldName(key)}',
    ].join(', ');
    final fields = StringBuffer();
    for (final key in envKeys) {
      final type = envDartType(config.flavors.map((f) => f.env[key]!));
      fields
        ..writeln()
        ..writeln('  /// `$key` from flavorpilot.yaml.')
        ..writeln('  final $type ${envFieldName(key)};');
    }

    changes.write(file.path, '''
$generatedHeader
import 'package:flutter/services.dart';

/// The flavors this app can be built with.
enum AppFlavor {
$values;

  const AppFlavor({$parameters});

  /// App name for this flavor.
  final String appName;
$fields
  /// The flavor the app is running with, taken from `flutter run --flavor`.
  static AppFlavor get current {
    final name = appFlavor;
    for (final flavor in values) {
      if (flavor.name == name) return flavor;
    }
    throw StateError(
      'Unknown flavor "\$name". Run the app with --flavor, '
      'e.g. `flavorpilot run <flavor>`.',
    );
  }
}
''');
    changes.note('Wrote lib/flavors.dart');
  }

  /// Creates one `lib/main_<flavor>.dart` per flavor.
  ///
  /// Existing files are kept, because the developer may already have added
  /// setup code to them.
  void _writeMainFiles(ProjectConfig config, FileChanges changes) {
    for (final flavor in config.flavors) {
      final entryPoint = config.entryPointFor(flavor)!;
      final file = File(p.join(projectDir, entryPoint));
      if (file.existsSync()) continue;

      changes.write(file.path, '''
import 'main.dart' as app;

/// Entry point for the "${flavor.name}" flavor.
///
/// Add setup code that only this flavor needs here (for example its own
/// Firebase project), then start the shared app.
void main() {
  app.main();
}
''');
      changes.note('Created $entryPoint');
    }
  }

  /// Writes an env [value] as Dart source code.
  String _literal(Object value) =>
      value is String ? "'${_escape(value)}'" : '$value';

  /// Escapes characters that are special inside single-quoted Dart strings.
  String _escape(String value) => value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
}
