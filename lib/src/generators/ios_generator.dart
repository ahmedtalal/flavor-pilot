import 'dart:io';

import 'package:path/path.dart' as p;

import '../models/project_config.dart';
import '../utils/file_changes.dart';
import 'generator.dart';
import 'ios/pbxproj_editor.dart';

/// Sets up flavors for iOS.
///
/// Flutter's `--flavor development` on iOS needs:
/// - build configurations named `Debug-development`, `Release-development`
///   and `Profile-development` in the Xcode project,
/// - a shared Xcode scheme named exactly `development` that uses them.
///
/// This generator creates both, and also:
/// - one xcconfig file per configuration in `ios/Flutter/flavorpilot/`,
///   which loads the matching CocoaPods settings,
/// - sets the app name in Info.plist to `$(FLAVOR_APP_NAME)`, so each
///   flavor shows its own name,
/// - maps the new configurations in `ios/Podfile`, if the project has one.
class IosGenerator extends Generator {
  IosGenerator({required super.projectDir, required super.logger});

  /// Value that makes Info.plist read the app name from the build settings.
  static const appNameVariable = r'$(FLAVOR_APP_NAME)';

  static const _podStartMarker = '# flavorpilot:start';
  static const _podEndMarker = '# flavorpilot:end';

  /// The display name entry in Info.plist. Groups: 1 = before value,
  /// 2 = value, 3 = after value.
  static final _displayName = RegExp(
    r'(<key>CFBundleDisplayName</key>\s*<string>)([^<]*)(</string>)',
  );

  String get _iosDir => p.join(projectDir, 'ios');
  String get _xcodeprojDir => p.join(_iosDir, 'Runner.xcodeproj');

  @override
  String get label => 'iOS';

  @override
  void generate(ProjectConfig config, FileChanges changes) {
    final pbxproj = File(p.join(_xcodeprojDir, 'project.pbxproj'));
    if (!pbxproj.existsSync()) {
      logger.warn('No ios/Runner.xcodeproj found, skipping iOS.');
      return;
    }

    // Throws if the project has hand-made flavor configurations.
    final editor = PbxprojEditor(pbxproj.readAsStringSync())
      ..removeGenerated()
      ..checkNoConflicts(config.flavors)
      ..addFlavors(config.flavors, defaultAppName: _originalAppName());
    changes
      ..write(pbxproj.path, editor.text)
      ..note(
        'Added ${config.flavors.length * PbxprojEditor.kinds.length} build '
        'configurations to ios/Runner.xcodeproj',
      );

    _writeXcconfigs(config, changes);
    _writeSchemes(config, changes);
    _updateInfoPlist(changes);
    _updatePodfile(config, changes);
  }

  /// The app name Info.plist shows today, used for builds without a flavor.
  ///
  /// Falls back to `$(PRODUCT_NAME)` (the target name) if it can't be found
  /// or was already switched to [appNameVariable] by an earlier run.
  String _originalAppName() {
    const fallback = r'$(PRODUCT_NAME)';
    final plist = File(p.join(_iosDir, 'Runner', 'Info.plist'));
    if (!plist.existsSync()) return fallback;

    final value = _displayName.firstMatch(plist.readAsStringSync())?[2];
    if (value == null || value == appNameVariable) return fallback;
    return _unescapeXml(value);
  }

  /// Writes one xcconfig per configuration, e.g.
  /// `ios/Flutter/flavorpilot/Debug-development.xcconfig`.
  ///
  /// The folder is deleted first, so files of removed flavors don't linger.
  void _writeXcconfigs(ProjectConfig config, FileChanges changes) {
    final dir = p.join(_iosDir, PbxprojEditor.xcconfigDir);
    changes.deleteDirectory(dir);

    for (final flavor in config.flavors) {
      for (final kind in PbxprojEditor.kinds) {
        final name = PbxprojEditor.configName(kind, flavor);
        // CocoaPods names its files after the configuration in lowercase.
        final pods =
            'Pods/Target Support Files/Pods-Runner/'
            'Pods-Runner.${name.toLowerCase()}.xcconfig';
        changes.write(p.join(dir, '$name.xcconfig'), '''
// GENERATED BY flavorpilot. Edit flavorpilot.yaml, not this file.
// Build settings for the "$name" configuration.
#include? "../../$pods"
#include "../Generated.xcconfig"
''');
      }
    }
    changes.note('Wrote xcconfig files in ios/${PbxprojEditor.xcconfigDir}');
  }

  /// Creates a shared scheme per flavor, copied from the Runner scheme.
  ///
  /// Existing schemes are left alone, since the developer may have changed
  /// them (for example to add environment variables).
  void _writeSchemes(ProjectConfig config, FileChanges changes) {
    final schemesDir = p.join(_xcodeprojDir, 'xcshareddata', 'xcschemes');
    final runnerScheme = File(p.join(schemesDir, 'Runner.xcscheme'));
    if (!runnerScheme.existsSync()) {
      logger.warn(
        'Runner.xcscheme not found, so iOS schemes were not created. Create '
        'a scheme per flavor in Xcode (Product > Scheme > New Scheme).',
      );
      return;
    }

    final template = runnerScheme.readAsStringSync();
    for (final flavor in config.flavors) {
      final file = File(p.join(schemesDir, '${flavor.name}.xcscheme'));
      if (file.existsSync()) continue;

      // Point every action (run, test, profile, archive) at this flavor's
      // configurations, e.g. "Debug" -> "Debug-development".
      changes
        ..write(
          file.path,
          template.replaceAllMapped(
            RegExp(r'buildConfiguration = "(Debug|Release|Profile)"'),
            (m) =>
                'buildConfiguration = "${PbxprojEditor.configName(m[1]!, flavor)}"',
          ),
        )
        ..note('Created iOS scheme "${flavor.name}"');
    }
  }

  /// Makes Info.plist show the per-flavor app name.
  void _updateInfoPlist(FileChanges changes) {
    final file = File(p.join(_iosDir, 'Runner', 'Info.plist'));
    if (!file.existsSync()) {
      logger.warn('ios/Runner/Info.plist not found, app names were not set.');
      return;
    }

    final content = file.readAsStringSync();
    final match = _displayName.firstMatch(content);
    if (match?[2] == appNameVariable) return; // Already done.

    final String updated;
    if (match != null) {
      updated = content.replaceFirst(
        _displayName,
        '${match[1]}$appNameVariable${match[3]}',
      );
    } else {
      // No display name yet: add it at the top of the main <dict>.
      updated = content.replaceFirst(
        '<dict>\n',
        '<dict>\n\t<key>CFBundleDisplayName</key>\n'
            '\t<string>$appNameVariable</string>\n',
      );
    }
    changes
      ..write(file.path, updated)
      ..note('Set the app name in ios/Runner/Info.plist');
  }

  /// Tells CocoaPods whether each new configuration is a debug or release
  /// build. Without this, CocoaPods treats them all as release builds.
  void _updatePodfile(ProjectConfig config, FileChanges changes) {
    final file = File(p.join(_iosDir, 'Podfile'));
    // Projects using Swift Package Manager may have no Podfile at all.
    if (!file.existsSync()) return;

    final content = file.readAsStringSync().replaceAll(
      RegExp(
        '[ \\t]*$_podStartMarker.*?$_podEndMarker[^\\n]*\\n?',
        dotAll: true,
      ),
      '',
    );
    final projectLine = RegExp(
      r"^project 'Runner', \{[ \t]*\n",
      multiLine: true,
    ).firstMatch(content);
    if (projectLine == null) {
      logger.warn(
        "Couldn't find \"project 'Runner', {\" in ios/Podfile. Map the "
        'Debug-*/Profile-*/Release-* configurations there by hand.',
      );
      return;
    }

    final block = StringBuffer()
      ..writeln(
        '  $_podStartMarker (generated, edit flavorpilot.yaml instead)',
      );
    for (final flavor in config.flavors) {
      block
        ..writeln("  '${PbxprojEditor.configName('Debug', flavor)}' => :debug,")
        ..writeln(
          "  '${PbxprojEditor.configName('Profile', flavor)}' => :release,",
        )
        ..writeln(
          "  '${PbxprojEditor.configName('Release', flavor)}' => :release,",
        );
    }
    block.writeln('  $_podEndMarker');

    changes
      ..write(
        file.path,
        content.replaceRange(projectLine.end, projectLine.end, '$block'),
      )
      ..note('Mapped the flavor configurations in ios/Podfile');
  }

  /// Turns XML escapes like `&amp;` back into normal characters.
  String _unescapeXml(String value) => value
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .replaceAll('&quot;', '"')
      .replaceAll('&apos;', "'")
      .replaceAll('&amp;', '&');
}
